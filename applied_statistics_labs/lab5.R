library(ggplot2)
library(readxl)

table <- read_excel("table.xlsx", sheet="Таблица")

df_raw <- data.frame(
  Регион = table$`Субъекты РФ`,
  ВРП = table$`Валовой региональный продукт`,
  Доходы = table$`Уровень доходов населения`,
  Тип_стар = table$`Тип региона`
)

df_raw <- na.omit(df_raw)

# Фактор A (расположение)

df_raw$Регион_тип <- ifelse(df_raw$Тип_стар == "с", "север",
                            ifelse(df_raw$Тип_стар == "ю", "юг",
                                   ifelse(df_raw$Тип_стар == "ц", "центр",
                                          ifelse(df_raw$Тип_стар == "в", "восток", NA))))

# Преобразуем в фактор с нужным порядком уровней
df_raw$Регион_тип <- factor(df_raw$Регион_тип, 
                            levels = c("север", "юг", "центр", "восток"))

# Проверяем распределение групп
cat("Распределение регионов по типам:\n")
print(table(df_raw$Регион_тип))

# Фактор B (ранг доходов)

# Разбиваем доходы на группы
income_breaks <- quantile(df_raw$Доходы, probs = c(0, 1/3, 2/3, 1), na.rm = TRUE)
df_raw$Ранг_доходов <- cut(df_raw$Доходы, 
                           breaks = income_breaks, 
                           include.lowest = TRUE, 
                           labels = c("низкий", "средний", "высокий"))
df_raw$Ранг_доходов <- factor(df_raw$Ранг_доходов, 
                              levels = c("низкий", "средний", "высокий"))

# 5.1. Однофакторный дисперсионный анализ (влияние фактора A на Y)

# Модель: Y ~ A
model_a <- aov(ВРП ~ Регион_тип, data = df_raw)

cat("\n========== 5.1. Однофакторный дисперсионный анализ ==========\n")
summary(model_a)

# Характеристики качества

# Коэффициент детерминации
ss_total <- sum((df_raw$ВРП - mean(df_raw$ВРП))^2)
r_squared <- summary(model_a)[[1]][["Sum Sq"]][1] / ss_total
cat("\nR-squared (доля объяснённой дисперсии):", round(r_squared, 4), "\n")

# Средние значения по группам
means <- tapply(df_raw$ВРП, df_raw$Регион_тип, mean)
cat("\nСредние значения ВРП по группам (млн руб.):\n")
print(round(means, 2))

# График
boxplot(ВРП ~ Регион_тип, data = df_raw,
        main = "ВРП в зависимости от расположения региона",
        xlab = "Тип региона", ylab = "Валовой региональный продукт (млн руб.)",
        col = c("lightblue", "lightgreen", "lightyellow", "lightpink"))
grid()

# 5.2. Двухфакторный дисперсионный анализ (влияние факторов A и B на Y)

cat("\n\n========== 5.2. Двухфакторный дисперсионный анализ ==========\n")

# Модель без взаимодействия Y ~ A + B
model_add <- aov(ВРП ~ Регион_тип + Ранг_доходов, data = df_raw)
cat("\nМодель без взаимодействия (аддитивная):\n")
summary(model_add)

# Модель с взаимодействием Y ~ A * B
model_inter <- aov(ВРП ~ Регион_тип * Ранг_доходов, data = df_raw)
cat("\nМодель с взаимодействием (A * B):\n")
summary(model_inter)

# Сравнение моделей
anova_compare <- anova(model_add, model_inter)
cat("\nСравнение аддитивной модели и модели с взаимодействием:\n")
print(anova_compare)

# График
print(ggplot(df_raw, aes(x = Регион_тип, y = ВРП, fill = Ранг_доходов)) +
        geom_boxplot() +
        labs(title = "Влияние расположения региона и ранга доходов на ВРП",
             x = "Тип региона", y = "ВРП (млн руб.)", fill = "Ранг доходов") +
        theme_minimal())

# Выводы на основе p-value

cat("\n========== ВЫВОДЫ ==========\n")

# Для 5.1

p_A <- summary(model_a)[[1]][["Pr(>F)"]][1]
if (p_A < 0.05) {
  cat("5.1. Влияние фактора A (расположение региона) на ВРП статистически значимо (p =", 
      round(p_A, 4), "). Гипотеза о несущественности отвергается\n")
} else {
  cat("5.1. Влияние фактора A на ВРП незначимо (p =", round(p_A, 4), 
      "). Гипотеза о несущественности не отвергается\n")
}

# Для 5.2

p_A_add <- summary(model_add)[[1]][["Pr(>F)"]][1]
p_B_add <- summary(model_add)[[1]][["Pr(>F)"]][2]
p_A_int <- summary(model_inter)[[1]][["Pr(>F)"]][1]
p_B_int <- summary(model_inter)[[1]][["Pr(>F)"]][2]
p_AB_int <- summary(model_inter)[[1]][["Pr(>F)"]][3]

cat("\n5.2. Модель без взаимодействия:\n")
cat("   Фактор A (регион): p =", round(p_A_add, 4), 
    ifelse(p_A_add < 0.05, "-> значим", "-> не значим"), "\n")
cat("   Фактор B (ранг доходов): p =", round(p_B_add, 4),
    ifelse(p_B_add < 0.05, "-> значим", "-> не значим"), "\n")

cat("\n   Модель с взаимодействием:\n")
cat("   Фактор A: p =", round(p_A_int, 4),
    ifelse(p_A_int < 0.05, "-> значим", "-> не значим"), "\n")
cat("   Фактор B: p =", round(p_B_int, 4),
    ifelse(p_B_int < 0.05, "-> значим", "-> не значим"), "\n")
cat("   Взаимодействие A:B: p =", round(p_AB_int, 4),
    ifelse(p_AB_int < 0.05, "-> значимо (совместное влияние есть)", 
           "-> незначимо (совместное влияние отсутствует)"), "\n")

cat("\nАнализ завершён.\n")